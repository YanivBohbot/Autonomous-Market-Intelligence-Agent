import { useEffect, useRef, useState } from "react";

import { getGeneratedReports, type GeneratedReportOption } from "../lib/api";
import { Icon } from "../ui/Icon";

interface EmailAttachmentSelectorProps {
  value: string;
  disabled?: boolean;
  onChange: (filename: string) => void;
}

function formatGeneratedAt(value: string): string {
  const date = new Date(value);
  return Number.isNaN(date.getTime())
    ? value
    : new Intl.DateTimeFormat(undefined, { dateStyle: "medium" }).format(date);
}

function formatSize(value: number): string {
  if (value < 1024) return `${value} B`;
  return `${(value / 1024).toFixed(1)} KB`;
}

export function EmailAttachmentSelector({
  value,
  disabled = false,
  onChange,
}: EmailAttachmentSelectorProps) {
  const [reports, setReports] = useState<GeneratedReportOption[]>([]);
  const [loading, setLoading] = useState(true);
  const [failed, setFailed] = useState(false);
  const valueRef = useRef(value);
  const onChangeRef = useRef(onChange);

  valueRef.current = value;
  onChangeRef.current = onChange;
  const selectedReport = reports.find((report) => report.filename === value);

  useEffect(() => {
    let active = true;
    setLoading(true);
    setFailed(false);

    const timer = window.setTimeout(async () => {
      try {
        const nextReports = await getGeneratedReports();
        if (!active) return;
        setReports(nextReports);
        if (
          valueRef.current
          && !nextReports.some((report) => report.filename === valueRef.current)
        ) {
          onChangeRef.current("");
        }
      } catch {
        if (!active) return;
        setReports([]);
        setFailed(true);
      } finally {
        if (active) setLoading(false);
      }
    }, 250);

    return () => {
      active = false;
      window.clearTimeout(timer);
    };
  }, []);

  return (
    <div className="rounded-2xl border border-terminal-border bg-[rgb(var(--surface-soft))] p-4">
      <div className="flex items-start gap-3">
        <span className="grid h-9 w-9 shrink-0 place-items-center rounded-xl bg-blue-50 text-blue-600 dark:bg-blue-950/50 dark:text-blue-300" aria-hidden="true">
          <Icon name="paperclip" className="h-4 w-4" />
        </span>
        <div className="min-w-0">
          <label htmlFor="email-attachment" className="text-sm font-semibold text-terminal-text">
            Attachment <span className="font-normal text-terminal-muted">(optional)</span>
          </label>
          <p className="mt-0.5 text-xs text-terminal-muted">Choose one report already generated by the system.</p>
        </div>
      </div>
      <select
        id="email-attachment"
        value={value}
        disabled={disabled || loading || reports.length === 0}
        onChange={(event) => onChange(event.target.value)}
        className="mt-3 w-full rounded-xl border border-terminal-border bg-terminal-panel px-3 py-2.5 text-sm text-terminal-text shadow-sm outline-none transition focus:border-blue-500 focus:ring-2 focus:ring-blue-500/15 disabled:cursor-not-allowed disabled:opacity-60"
      >
        <option value="">No attachment</option>
        {reports.map((report) => (
          <option key={report.filename} value={report.filename}>
            {report.client_name} · {report.filename} · {formatGeneratedAt(report.generated_at)}
          </option>
        ))}
      </select>
      {loading && <span role="status" className="mt-2 block text-xs text-terminal-muted">Loading generated reports…</span>}
      {!loading && failed && <span role="alert" className="mt-2 block text-xs text-terminal-danger">Generated reports unavailable</span>}
      {!loading && !failed && reports.length === 0 && (
        <span className="mt-2 block text-xs text-terminal-muted">No generated reports available</span>
      )}
      {selectedReport && (
        <div className="mt-3 flex flex-col gap-3 rounded-xl border border-blue-200 bg-blue-50 p-3 sm:flex-row sm:items-center dark:border-blue-900 dark:bg-blue-950/30">
          <span className="grid h-10 w-10 shrink-0 place-items-center rounded-lg bg-white text-blue-600 shadow-sm dark:bg-blue-950 dark:text-blue-300" aria-hidden="true">
            <Icon name="document" className="h-5 w-5" />
          </span>
          <div className="min-w-0 flex-1">
            <p className="text-[11px] font-semibold uppercase tracking-[0.12em] text-blue-700 dark:text-blue-300">Selected report</p>
            <p className="mt-0.5 text-sm font-semibold text-terminal-text">{selectedReport.client_name}</p>
            <p className="truncate font-mono text-[11px] text-terminal-muted" title={selectedReport.filename}>{selectedReport.filename}</p>
            <p className="mt-1 text-[11px] text-terminal-muted">{formatGeneratedAt(selectedReport.generated_at)} · {formatSize(selectedReport.size_bytes)}</p>
          </div>
          <button
            type="button"
            disabled={disabled}
            onClick={() => onChange("")}
            className="inline-flex min-h-9 items-center justify-center gap-1.5 rounded-lg border border-terminal-border bg-terminal-panel px-3 text-xs font-semibold text-terminal-muted transition hover:border-red-200 hover:text-terminal-danger focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-blue-500 disabled:cursor-not-allowed disabled:opacity-50"
          >
            <Icon name="close" className="h-3.5 w-3.5" />
            Remove attachment
          </button>
        </div>
      )}
    </div>
  );
}
